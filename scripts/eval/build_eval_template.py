def main() -> None:
    rows = []
    for cid, cat, text, expect, rt, s, e, c in CASES:
        try:
            it = parse_safe(text)
            if it.need_clarify:  # 被安全网关拦截
                pred = [f"BLOCKED:{it.blocked}", "-", "-", "-"]
            else:
                pred = [it.report_type, it.start, it.end, (it.country or "ALL")]
        except Exception as ex:  # 解析器崩溃也是评测结果，记为 CRASH
            pred = ["CRASH", type(ex).__name__, str(ex)[:60], "CRASH"]
        rows.append([cid, cat, text, expect, rt, s, e, c, "", ""] + pred)

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(rows)

    payload = [
        {
            "id": cid, "category": cat, "instruction": text, "expect": expect,
            "golden": {"report_type": rt, "start": s, "end": e, "country": c},
        }
        for cid, cat, text, expect, rt, s, e, c in CASES
    ]
    OUT_JSON.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    # 留出集
    hrows = []
    for cid, cat, text, expect, rt, s, e, c in HOLDOUT:
        hrows.append([cid, cat, text, expect, rt, s, e, c, "", ""])
    with HOLD_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        w.writerows(hrows)

    print(f"OK  主集 {len(rows)} 条 / 留出集 {len(hrows)} 条")
    print(f"CSV : {OUT_CSV}")
    print(f"CSV : {HOLD_CSV}")
    print(f"JSON: {OUT_JSON}")


if __name__ == "__main__":
    main()
